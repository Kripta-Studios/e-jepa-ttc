"""Regenerate completed Dfull and ranking-screen tables from recorded evidence."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def main() -> None:
    """Render development results without implying official or TTC validation."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--evidence", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    final = json.loads((args.evidence / "dfull_final_model.json").read_text())
    ranking = json.loads((args.evidence / "ranking_screen.json").read_text())
    metrics = final["selected_evaluation"]["metrics"]
    rows = [
        "# Dfull and post-Dfull development evidence",
        "",
        "Generated by `scripts/report_detection_followup.py` from the adjacent JSON evidence.",
        "These are development-selection results; they do not establish official eAP SOTA,",
        "independent generalization, eight-class production readiness, or improved TTC.",
        "",
        "## Completed Dfull",
        "",
        f"Unique train frames: {final['unique_train_frames']:,}. "
        f"Exposures: {final['run_exposures']:,}.",
        f"Selected checkpoint update: {final['checkpoint_update']:,}.",
        f"Checkpoint SHA-256: `{final['checkpoint_sha256']}`.",
        f"Full-selection frames: {metrics['sample_count']:,}; AP: **{metrics['AP']:.8f}**.",
        "",
        "| Class | Full-selection AP |",
        "|---|---:|",
    ]
    for name, value in metrics["per_class_AP"].items():
        rows.append(f"| {name} | {value:.8f} |")
    rows.extend(
        [
            "",
            "## Fixed-pool ranking screen",
            "",
            "The ranker was fitted only on 4,096 TRAIN frames. The comparison uses the same",
            "1,024 selection frames and identical proposal geometry. It is not directly",
            "comparable to the full-selection AP above.",
            "",
            "| Method | Panel AP |",
            "|---|---:|",
        ]
    )
    for name, result in ranking["results"].items():
        rows.append(f"| {name} | {result['AP']:.8f} |")
    rows.extend(
        [
            "",
            f"Absolute learned-ranking gain: {ranking['gain']:.8f}.",
            "",
            "| Class | Baseline panel AP | Learned-ranking panel AP |",
            "|---|---:|---:|",
        ]
    )
    baseline = ranking["results"]["baseline"]
    learned = ranking["results"]["learned"]
    for name, value in baseline["per_class"].items():
        rows.append(f"| {name} | {value:.8f} | {learned['per_class'][name]:.8f} |")
    improved = sum(
        learned["by_sequence"][s]["AP"] > r["AP"] for s, r in baseline["by_sequence"].items()
    )
    rows.extend(
        [
            "",
            f"Sequence-level panel AP improved in {improved}/"
            f"{len(baseline['by_sequence'])} sequences.",
            "Bicycle AP decreased; rare-class coverage remains a limitation. The scalar",
            "uncertainty control is not a calibrated probability. The monotonic control",
            "preserved AP exactly. Full-selection confirmation is a separate pending result.",
            "",
            "## Interpretation and continuation",
            "",
            "S3 screening compares four seed-7 continuations from the selected Dfull parent:",
            "current only, repeated current, one past frame, and two past frames. Each receives",
            "1,024 updates, batch four, LR 2e-5 with the same schedule and selection panel.",
            "A temporal arm must exceed both controls by at least 0.005 AP to pass this screen.",
            "Exact zero-update output parity was verified against the frozen parent "
            "before training.",
            "",
            "The event-input cache is prepared locally from public TRAIN/selection streams:",
            "50 ms windows ending at RGB exposure end, five bins per polarity, 160x96, FP32",
            "with lossless compression and per-window normalization. It reads no object labels",
            "and performs no GPU training. HDF5 source hashes and output hashes are verified.",
            "S4 training, independent TTC producers, end-to-end TTC evaluation and official",
            "benchmark comparison remain separate gates.",
            "",
        ]
    )
    temporal_path = args.evidence / "temporal_screen.json"
    if temporal_path.exists():
        temporal = json.loads(temporal_path.read_text())
        rows.extend(
            ["## Completed temporal screen", "", "| Arm | Final-update panel AP |", "|---|---:|"]
        )
        for name, result in temporal["variants"].items():
            rows.append(f"| {name} | {result['AP']:.8f} |")
        rows.extend(
            [
                "",
                f"Temporal gate passed: **{temporal['screening_pass']}**.",
                "Best temporal gain over the strongest control: "
                f"{temporal['gain_over_strongest_control']:.8f}.",
                "The monocular detector remains the base. This short, single-seed screen",
                "does not establish convergence or rule out other temporal recipes.",
                "",
            ]
        )
    smoke_path = args.evidence / "event_gpu_smoke.json"
    if smoke_path.exists():
        smoke = json.loads(smoke_path.read_text())
        rows.extend(
            [
                "## Event adapter engineering gate",
                "",
                f"GPU admission: **{smoke['status']}**; optimizer updates: "
                f"{smoke['optimizer_updates']}; finite gradient tensors: "
                f"{smoke['gradient_tensors']}.",
                "Nonzero synthetic event inputs with real label-free RGB preserve the",
                "initial detector outputs exactly for F01 and F11. Model state is unchanged.",
                "This validates integration and gradients, not real-event accuracy.",
                "",
            ]
        )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(rows), encoding="utf-8")


if __name__ == "__main__":
    main()
