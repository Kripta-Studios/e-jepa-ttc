"""Run the full MonoDGP portable variant without external CUDA compilation.

This is a synthetic software check, not an eAP evaluation or pretrained model.
Source changes are generated from a fixed upstream revision and saved as a patch.
The functions build_detector and decode_native are reusable by bounded pilots.
"""

