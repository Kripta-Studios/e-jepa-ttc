"""Generate paper tables from bundled middle-period machine-readable evidence."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = json.loads((ROOT / "data/middle_results.json").read_text(encoding="utf-8"))
TABLES = ROOT / "tables"
TABLES.mkdir(exist_ok=True)


def tex(value: object) -> str:
    return str(value).replace("_", r"\_").replace("%", r"\%")


def write(
    name: str,
    caption: str,
    label: str,
    spec: str,
    header: list[str],
    rows: list[str],
    note: str,
) -> None:
    content = "\n".join(
        [
            r"% Generated by research/middle_tables.py; do not edit numeric values.",
            r"\begin{table}[tbp]",
            r"\centering\small",
            r"\caption{" + caption + "}",
            r"\label{" + label + "}",
            r"\setlength{\tabcolsep}{5pt}",
            r"\begin{tabular}{" + spec + "}",
            r"\toprule",
            " & ".join(header) + r" \\",
            r"\midrule",
            *rows,
            r"\bottomrule",
            r"\end{tabular}",
            r"\par\vspace{4pt}",
            r"\begin{minipage}{0.98\linewidth}\footnotesize " + note + r"\end{minipage}",
            r"\end{table}",
            "",
        ]
    )
    (TABLES / name).write_text(content, encoding="utf-8")


rows = []
for key, label in [
    ("7", "7 (observed)"),
    ("13", "13"),
    ("23", "23"),
    ("new13_23", "New seeds 13/23"),
    ("all7_13_23", "All three seeds"),
]:
    d = DATA["h16_replication"][key]
    lo, hi = d["hierarchical_ci95"]
    if key == "new13_23":
        rows.append(r"\midrule")
    rows.append(
        f"{label} & {d['h8_mid']:.3f} & {d['h16_mid']:.3f} & "
        f"{d['paired_loss_delta']:+.3f} & [{lo:+.3f}, {hi:+.3f}]" + r" \\"
    )
write(
    "middle_replication.tex",
    "H16 and H8 temporal heads on OLD\\_DEV.",
    "tab:middle-replication",
    "lrrrr",
    ["Head seed(s)", "H8 MiD", "H16 MiD", r"$\Delta$ MiD", r"Hierarchical 95\% CI"],
    rows,
    r"Nine sequences, 8,192 queries, and three folds. Delta is H16 minus H8; "
    r"multi-seed rows average paired losses. Seed 7 had been evaluated previously. "
    r"All heads share fixed expert producers. \evidence{M_SIMPLEX}",
)

rows = []
for stage in ["61", "62"]:
    rows.append(r"\multicolumn{4}{l}{\textbf{Stage " + stage + r"}} \\")
    for arm, d in DATA["stages"][stage]["summaries"].items():
        rows.append(
            f"{tex(arm)} & {d['sequence_macro_paper_MiD_overall']:.3f} & {d['rows']:,} & "
            f"{100 * d['finite_fraction']:.0f}\\%" + r" \\"
        )
    if stage == "61":
        rows.append(r"\midrule")
write(
    "middle_mechanisms.tex",
    "Pair routing (Stage 61) and local-field experiments (Stage 62).",
    "tab:middle-mechanisms",
    r"l@{\hspace{18pt}}r@{\hspace{18pt}}r@{\hspace{18pt}}r",
    ["Arm", "MiD", "Queries", "Finite"],
    rows,
    r"Sequence-macro MiD, evaluated on nine sequences and three folds per stage. "
    r"Lower is better. \evidence{M_STAGE61,M_STAGE62}",
)

labels = {
    "H8_seed7": "H8 / head 7",
    "H8_seed13": "H8 / head 13",
    "H8_seed23": "H8 / head 23",
    "public_Garl_event_lhr": "Garl event",
    "public_Garl_rgb_event_full": "Garl RGB + event",
}
cohorts = {
    "V12_EVTTC_946": "EvTTC: 946 eligible / 1,024 queries; 32 sequences",
    "V12_EVTTC_3640": "EvTTC expanded: 3,640 / 3,947; same 32 sequences",
    "V12_FCWD_597": "FCWD: 597 / 630; three sequences",
}
rows = []
for idx, (cohort, d) in enumerate(DATA["transfer"].items()):
    if idx:
        rows.append(r"\midrule")
    rows.append(r"\multicolumn{5}{l}{\textbf{" + cohorts[cohort] + r"}} \\")
    for m in d["models"]:
        rows.append(
            f"{labels[m['model']]} & {m['mae_seconds']:.3f} & "
            f"{m['median_absolute_error_seconds']:.3f} & {m['rmse_seconds']:.3f} & "
            f"{m['rte_percent']:.2f}" + r" \\"
        )
write(
    "middle_transfer.tex",
    "Frozen H8 and Garl models evaluated on EvTTC and FCWD.",
    "tab:middle-transfer",
    "lrrrr",
    ["Method", "MAE (s)", "Median AE (s)", "RMSE (s)", r"RTE (\%)"],
    rows,
    r"Scores use queries with valid TTC targets; prediction coverage is 100\% on these "
    r"queries. H8 bounds TTC at $\pm60$\,s, while Garl retains its native signed outputs. "
    r"The FCWD comparison uses event-only inputs. "
    r"\evidence{M_V12_EVTTC_946,M_V12_EVTTC_3640,M_V12_FCWD_597}",
)

route = {r["model"]: r for r in DATA["shared_route_cost"]}
rows = []
for d in DATA["head_cost"]:
    r = route[d["model"]]
    rows.append(
        f"{tex(d['model'])} & {float(d['MiD']):.3f} & "
        f"{float(d['p95_median_ms']):.2f} & "
        f"{float(r['warm_total_p95_block1_ms']) / 1000:.3f} & "
        f"{float(r['warm_total_p95_block2_ms']) / 1000:.3f}" + r" \\"
    )
write(
    "middle_cost.tex",
    "Head-only and full-pipeline runtime.",
    "tab:middle-cost",
    r"l@{\hspace{12pt}}r@{\hspace{12pt}}r@{\hspace{12pt}}r@{\hspace{12pt}}r",
    ["Model", "MiD", r"Head p95 (ms)", r"Route 1 p95 (s)", r"Route 2 p95 (s)"],
    rows,
    r"Head: median of three blockwise p95 values, CPU FP32, prepared inputs, 500 "
    r"measurements per block. Route: p95 on 64 TRAIN queries with supplied ROI, shared "
    r"GPU, and resident producers. Accuracy uses OLD\_DEV seed 7, nine sequences and "
    r"three folds. \evidence{M_HEAD_COST,M_ROUTE_COST}",
)
print("Generated four tables from bundled JSON.")
